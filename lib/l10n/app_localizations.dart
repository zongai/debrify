/// App UI strings. Prefer [AppLocalizations.of] in widgets.
///
/// - Named getters (`cancel`, `settings`, …) for code that already uses keys.
/// - [t] translates an English UI phrase when the locale is zh/ja.
///   Settings tiles auto-call [t] so SettingsRows English copy localizes.
class AppLocalizations {
  AppLocalizations._(this.locale, this._t);

  final Locale locale;
  final Map<String, String> _t;

  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale('zh'),
    Locale('ja'),
  ];

  static const languageOptions = <(String code, String nativeName)>[
    ('system', 'System'),
    ('en', 'English'),
    ('zh', '中文'),
    ('ja', '日本語'),
  ];

  static AppLocalizations of(BuildContext context) {
    final value = Localizations.of<AppLocalizations>(context, AppLocalizations);
    assert(value != null, 'AppLocalizations not found in context');
    return value!;
  }

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations lookup(Locale locale) {
    final language = locale.languageCode.toLowerCase();
    if (_tables.containsKey(language)) {
      return AppLocalizations._(Locale(language), _tables[language]!);
    }
    return AppLocalizations._(const Locale('en'), _tables['en']!);
  }

  String _s(String key) => _t[key] ?? _tables['en']![key] ?? key;

  /// Translate a source English UI string for the active locale.
  /// Returns [source] unchanged for English or unknown phrases.
  String t(String source) {
    if (source.isEmpty) return source;
    final lang = locale.languageCode;
    if (lang == 'en') return source;
    final phrases = _phraseTables[lang];
    if (phrases == null) return source;
    return phrases[source] ?? source;
  }

  // --- Common ---
  String get appName => _s('appName');
